import os  # 파일 경로를 다루는 파이썬 기본 모듈


def dp(name):
    """
    실행 위치가 어디든 데이터 폴더를 찾아주는 작은 도우미 함수
    """
    here = os.path.dirname(os.path.abspath(__file__))
    for c in (
        os.path.join("data", name),
        os.path.join(here, "data", name),
        os.path.join(here, "..", "data", name),
    ):
        if os.path.exists(c):
            return c
    return os.path.join("data", name)


